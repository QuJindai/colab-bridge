create function public.colab_bridge_publish_artifact(
  p_runtime_id uuid,
  p_job_id uuid,
  p_lease_token uuid,
  p_artifact_id uuid
) returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_job public.colab_bridge_jobs%rowtype;
  v_artifact public.colab_bridge_artifacts%rowtype;
begin
  select * into v_job from public.colab_bridge_jobs where id = p_job_id for update;
  if not found or v_job.runtime_id is distinct from p_runtime_id or v_job.lease_token is distinct from p_lease_token
    or v_job.status not in ('running', 'cancelling') or v_job.lease_expires_at <= clock_timestamp() then
    return jsonb_build_object('ok', false, 'error_code', 'LEASE_INVALID');
  end if;
  select * into v_artifact from public.colab_bridge_artifacts
    where id = p_artifact_id and job_id = p_job_id and runtime_id = p_runtime_id and attempt = v_job.attempt
    for update;
  if not found then return jsonb_build_object('ok', false, 'error_code', 'ARTIFACT_NOT_FOUND'); end if;
  if v_artifact.status = 'prepared' then
    update public.colab_bridge_artifacts
      set status = 'published', published_at = clock_timestamp()
      where id = p_artifact_id;
  end if;
  return jsonb_build_object('ok', true, 'artifact_id', p_artifact_id);
end;
$$;

create function public.colab_bridge_list_artifacts(p_job_id uuid) returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_artifacts jsonb;
begin
  if not exists (select 1 from public.colab_bridge_jobs where id = p_job_id) then
    return jsonb_build_object('ok', false, 'error_code', 'JOB_NOT_FOUND');
  end if;
  select coalesce(jsonb_agg(to_jsonb(a) - 'storage_path' order by a.created_at), '[]'::jsonb)
    into v_artifacts
  from public.colab_bridge_artifacts a
  where a.job_id = p_job_id and a.status = 'published';
  return jsonb_build_object('ok', true, 'artifacts', v_artifacts);
end;
$$;

