    if v_artifact.bytes = p_bytes and v_artifact.sha256 = p_sha256 and v_artifact.mime_type = p_mime_type
      and v_artifact.status = 'prepared' then
      return jsonb_build_object('ok', true, 'artifact_id', v_artifact.id, 'storage_path', v_artifact.storage_path);
    end if;
    return jsonb_build_object('ok', false, 'error_code', 'ARTIFACT_CONFLICT');
  end if;
  v_storage_path := p_runtime_id::text || '/' || p_job_id::text || '/' || v_job.attempt::text || '/' || v_id::text;
  insert into public.colab_bridge_artifacts (
    id, job_id, runtime_id, attempt, path, storage_path, bytes, sha256, mime_type
  ) values (
    v_id, p_job_id, p_runtime_id, v_job.attempt, p_path, v_storage_path, p_bytes, p_sha256, p_mime_type
