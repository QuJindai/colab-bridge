create function public.colab_bridge_prepare_artifact(
  p_runtime_id uuid,
  p_job_id uuid,
  p_lease_token uuid,
  p_path text,
  p_bytes bigint,
  p_sha256 text,
  p_mime_type text
) returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_job public.colab_bridge_jobs%rowtype;
  v_artifact public.colab_bridge_artifacts%rowtype;
  v_id uuid := gen_random_uuid();
  v_storage_path text;
begin
  select * into v_job from public.colab_bridge_jobs where id = p_job_id for update;
  if not found or v_job.runtime_id is distinct from p_runtime_id or v_job.lease_token is distinct from p_lease_token
    or v_job.status not in ('running', 'cancelling') or v_job.lease_expires_at <= clock_timestamp() then
    return jsonb_build_object('ok', false, 'error_code', 'LEASE_INVALID');
  end if;
  if p_bytes < 0 or p_sha256 !~ '^[0-9a-f]{64}$' or length(p_mime_type) not between 1 and 200
    or length(p_path) not between 1 and 512 or p_path ~ '(^/|\\\\|(^|/)\\.\\.?(/|$)|/$)' then
