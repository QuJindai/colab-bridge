      where id = p_job_id and runtime_id = p_runtime_id and lease_token = p_lease_token;
    return jsonb_build_object('ok', true, 'lease_valid', false, 'cancel_requested', v_job.cancel_requested_at is not null);
  end if;
  update public.colab_bridge_jobs
    set lease_expires_at = v_now + interval '60 seconds', updated_at = v_now
    where id = p_job_id and runtime_id = p_runtime_id and lease_token = p_lease_token;
  return jsonb_build_object('ok', true, 'lease_valid', true, 'cancel_requested', v_job.status = 'cancelling' or v_job.cancel_requested_at is not null);
end;
$$;

